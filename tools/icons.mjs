#!/usr/bin/env node
/**
 * ANTZ Rounded icons (icons/antz-rounded/): build the sprite, apply the UI replacements, generate the docs grid.
 *
 *   node tools/icons.mjs           write icons/antz-rounded/sprite.svg, update the #i-* symbols in assets/site.js
 *                                  listed in replacements.json, and the grid in docs-src/icon-library.html
 *   node tools/icons.mjs --check   exit 1 if any of those is out of date (used by tools/test.mjs)
 *
 * Zero dependencies. Source files are never changed; ids inside each icon are prefixed so masks never clash.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'icons/antz-rounded');
const CHECK = process.argv.includes('--check');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const stale = [];
function out(rel, text) {
  const p = path.join(ROOT, rel);
  const old = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  if (old === text) return;
  if (CHECK) stale.push(rel); else fs.writeFileSync(p, text);
}

const index = JSON.parse(read('icons/antz-rounded/index.json'));
const icons = index.icons;
const NAME = /^[a-z0-9_]+$/;

// Inner markup of an icon SVG, compacted, with ids prefixed (mask ids are the only ids the style allows)
function inner(file, prefix) {
  const svg = fs.readFileSync(path.join(DIR, file), 'utf8');
  if (/<script|on[a-z]+\s*=|href\s*=\s*"(?!#)|<foreignObject/i.test(svg)) throw new Error(`${file}: unsafe content`);
  let body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const ids = [...body.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
  for (const id of ids) body = body.replaceAll(`id="${id}"`, `id="${prefix}-${id}"`).replaceAll(`url(#${id})`, `url(#${prefix}-${id})`);
  return body.replace(/\s*\n\s*/g, '').trim();
}

// 1. Sprite: antz-<name> (line, 2px as drawn) and antz-<name>-filled
const symbols = [];
for (const ic of icons) {
  if (!NAME.test(ic.name)) throw new Error(`index.json: bad name ${ic.name}`);
  for (const [style, id, wrap] of [['line', `antz-${ic.name}`, 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'], ['filled', `antz-${ic.name}-filled`, 'fill="currentColor" stroke="none"']]) {
    const f = `${style}/${ic.name}.svg`;
    if (!fs.existsSync(path.join(DIR, f))) throw new Error(`missing ${f}`);
    symbols.push(`<symbol id="${id}" viewBox="0 0 24 24"><g ${wrap}>${inner(f, id)}</g></symbol>`);
  }
}
out('icons/antz-rounded/sprite.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">\n<!-- ANTZ Rounded ${icons.length} icons, line (antz-<name>) and filled (antz-<name>-filled). Generated by tools/icons.mjs. -->\n${symbols.join('\n')}\n</svg>\n`);

// 2. UI icons: draw the listed #i-* symbols in assets/site.js with their ANTZ Rounded equivalent
const map = JSON.parse(read('icons/antz-rounded/replacements.json'));
let js = read('assets/site.js');
for (const [ui, name] of Object.entries(map.replace)) {
  if (!icons.some((i) => i.name === name)) throw new Error(`replacements.json: ${name} is not in index.json`);
  const re = new RegExp(`(<symbol id=\\\\"i-${ui}\\\\" viewBox=\\\\"0 0 24 24\\\\">)([\\s\\S]*?)(</symbol>)`);
  if (!re.test(js)) throw new Error(`assets/site.js: no symbol i-${ui}`);
  const body = inner(`line/${name}.svg`, `i-${ui}`).replace(/"/g, '\\"');
  js = js.replace(re, (_, a, __, c) => `${a}${body}${c}`);
}
out('assets/site.js', js);

// 3. Docs grid (between markers in docs-src/icon-library.html)
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const byModule = new Map();
for (const ic of icons) { if (!byModule.has(ic.module)) byModule.set(ic.module, []); byModule.get(ic.module).push(ic); }
const glyph = (id) => `<svg class="ar-glyph" aria-hidden="true"><use href="#${id}"/></svg>`;
const grid = [...byModule].map(([mod, list]) => `<h4>${esc(mod)} <span class="t-caption">${list.length}</span></h4>\n<div class="ar-grid">${list.map((ic) =>
  `<button type="button" class="ar-tile" data-copy="antz-${ic.name}" data-search="${esc([ic.name, ic.label, ic.module, ...(ic.tags || [])].join(' ').toLowerCase())}" aria-label="${esc(ic.label)}: copy antz-${ic.name}">${glyph(`antz-${ic.name}`)}${glyph(`antz-${ic.name}-filled`)}<b>${esc(ic.label)}</b><code>${ic.name}</code>${ic.status === 'approved' ? '' : `<span class="status status--plain status--caution">${esc(ic.status === 'draft' ? 'Draft' : ic.status)}</span>`}</button>`).join('')}</div>`).join('\n');
const pairs = Object.entries(map.replace).map(([ui, name]) => `<tr><td><svg class="icon" aria-hidden="true"><use href="#i-${ui}"/></svg> <code>i-${ui}</code></td><td><code>antz-${name}</code></td></tr>`).join('');
const kept = Object.entries(map.kept).map(([ui, why]) => `<tr><td><svg class="icon" aria-hidden="true"><use href="#i-${ui}"/></svg> <code>i-${ui}</code></td><td>${esc(why)}</td></tr>`).join('');
const prim = JSON.parse(read('icons/antz-rounded/primary/index.json'));
const ptiles = prim.icons.sort((a, b) => (a.order || 0) - (b.order || 0)).map((p) => `<figure class="ar-prim"><img src="../icons/antz-rounded/primary/${esc(p.svg)}" alt="" width="48" height="48" loading="lazy"><figcaption><b>${esc(p.label)}</b><span class="t-caption">${esc(p.module)}</span></figcaption></figure>`).join('');
const docs = 'docs-src/icon-library.html';
if (fs.existsSync(path.join(ROOT, docs))) {
  const src = read(docs)
    .replace(/<!-- antz-icons:start -->[\s\S]*?<!-- antz-icons:end -->/, `<!-- antz-icons:start -->\n${grid}\n<!-- antz-icons:end -->`)
    .replace(/<!-- antz-pairs:start -->[\s\S]*?<!-- antz-pairs:end -->/, `<!-- antz-pairs:start -->${pairs}<!-- antz-pairs:end -->`)
    .replace(/<!-- antz-kept:start -->[\s\S]*?<!-- antz-kept:end -->/, `<!-- antz-kept:start -->${kept}<!-- antz-kept:end -->`)
    .replace(/<!-- antz-primary:start -->[\s\S]*?<!-- antz-primary:end -->/, `<!-- antz-primary:start --><div class="ar-prims">${ptiles}</div><!-- antz-primary:end -->`);
  out(docs, src);
}

if (CHECK) {
  if (stale.length) { console.error(`✗ ANTZ Rounded icons out of date: ${stale.join(', ')}. Run node tools/icons.mjs.`); process.exit(1); }
  console.log(`✓ ANTZ Rounded icons up to date (${icons.length} icons, ${Object.keys(map.replace).length} UI replacements).`);
} else console.log(`✓ ANTZ Rounded: sprite with ${icons.length * 2} symbols, ${Object.keys(map.replace).length} UI icons redrawn, docs grid updated.`);
